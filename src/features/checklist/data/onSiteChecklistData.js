// ==========================================
// 카테고리 항목에 category 필드를 채워서 평탄화
// ==========================================
const FLAT_CATEGORY_ITEMS = Object.entries(CATEGORY_ITEMS).flatMap(
  ([category, items]) =>
    items.map((item) => ({
      ...item,
      category,
    })),
);

// ==========================================
// 필수확인 탭 / 상세 페이지에서 id로 바로 찾을 수 있도록 전체를 합친 배열
// ==========================================
export const ALL_ITEMS_FLAT = [...BASE_ITEMS, ...FLAT_CATEGORY_ITEMS];

// ==========================================
// id로 항목 정보를 찾는 헬퍼
// ==========================================
export function getChecklistItemById(id) {
  return ALL_ITEMS_FLAT.find((item) => item.id === id) || null;
}

// ==========================================
// 상세 페이지에서 사용할 상세 콘텐츠
// ==========================================
export function getDetailContent(item) {
  if (!item) {
    return null;
  }

  return {
    title: `${item.title} 확인`,
    whyText: item.whyText || "",
    howSteps: item.howSteps || [],
    warningText: item.warningText || "",
  };
}
